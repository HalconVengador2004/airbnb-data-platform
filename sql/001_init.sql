CREATE UNIQUE INDEX IF NOT EXISTS ux_listings_city_scrape_id_id
    ON raw.listings (_city, scrape_id, id);

CREATE INDEX IF NOT EXISTS ix_listings_city_scrape
    ON raw.listings (_city, scrape_id);

CREATE TABLE IF NOT EXISTS ingestion.file_manifest (
    dataset TEXT NOT NULL,
    city TEXT NOT NULL,
    scrape_id TEXT NOT NULL,
    source_file TEXT NOT NULL,
    file_hash TEXT NOT NULL,
    row_count INTEGER NOT NULL CHECK (row_count >= 0),
    status TEXT NOT NULL CHECK (status IN ('loaded', 'failed')),
    error_message TEXT,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (dataset, city, scrape_id)
);

CREATE INDEX IF NOT EXISTS ix_file_manifest_hash
    ON ingestion.file_manifest (dataset, city, file_hash);
